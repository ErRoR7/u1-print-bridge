def test_parse_estimates_from_gcode_comments(worker, tmp_path):
    gcode = tmp_path / "plate_1.gcode"
    gcode.write_text(
        "; generated by OrcaSlicer\n"
        "; estimated printing time (normal mode) = 2h 15m 30s\n"
        "; filament used [g] = 12.50, 3.25\n"
    )
    est = worker.parse_estimates("Slicing finished", gcode)
    assert est["time_s"] == 2 * 3600 + 15 * 60 + 30
    assert est["filament_g"] == 15.75
    assert est["filament_g_by_tool"] == {"T0": 12.5, "T1": 3.25}


