def test_arrange_copies_grid(worker, tmp_path):
    import re as _re
    src = _make_box_3mf(tmp_path / "box.3mf")
    dst = tmp_path / "copies.3mf"
    info = worker.arrange_copies(src, dst, 4)
    assert (info["cols"], info["rows"]) == (2, 2)
    assert info["footprint"] == [10.0, 20.0]
    data = zipfile.ZipFile(dst).read("3D/3dmodel.model").decode()
    items = _re.findall(r"<item\b[^>]*?/>", data)
    assert len(items) == 4
    ts = [[float(v) for v in _re.search(r'transform="([^"]+)"', i).group(1).split()]
          for i in items]
    # 2x2 grid of 10x20 with 8mm gap, centered on original center (5, 10)
    assert sorted(t[3] for t in ts) == [-9.0, -9.0, 9.0, 9.0]
    assert sorted(t[7] for t in ts) == [-14.0, -14.0, 14.0, 14.0]


