def _make_box_3mf(path, wx=10.0, wy=20.0, wz=30.0, transform=None):
    verts = "".join(
        '<vertex x="%s" y="%s" z="%s"/>\n' % (x, y, z)
        for x in (0, wx) for y in (0, wy) for z in (0, wz))
    obj = ('<object id="2" type="model"><mesh><vertices>%s</vertices>'
           '<triangles><triangle v1="0" v2="1" v3="2"/></triangles></mesh></object>' % verts)
    tattr = ' transform="%s"' % transform if transform else ""
    model = ('<?xml version="1.0"?><model unit="millimeter"><resources>%s</resources>'
             '<build><item objectid="2"%s/></build></model>' % (obj, tattr))
    with zipfile.ZipFile(path, "w") as zf:
        zf.writestr("[Content_Types].xml", "<Types/>")
        zf.writestr("3D/3dmodel.model", model)
    return path


def _bbox_of(path):
    import re as _re
    data = zipfile.ZipFile(path).read("3D/3dmodel.model").decode()
    xs = [float(v) for v in _re.findall(r'x="([\d.\-]+)"', data)]
    ys = [float(v) for v in _re.findall(r'y="([\d.\-]+)"', data)]
    zs = [float(v) for v in _re.findall(r'z="([\d.\-]+)"', data)]
    return (round(max(xs) - min(xs), 1), round(max(ys) - min(ys), 1),
            round(max(zs) - min(zs), 1))


