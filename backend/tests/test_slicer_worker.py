def test_arrange_copies_composes_existing_transform(worker, tmp_path):
    import re as _re
    src = _make_box_3mf(tmp_path / "box.3mf",
                        transform="1 0 0 100 0 1 0 50 0 0 1 0")
    dst = tmp_path / "moved.3mf"
    worker.arrange_copies(src, dst, 2)
    data = zipfile.ZipFile(dst).read("3D/3dmodel.model").decode()
    ts = [[float(v) for v in m.group(1).split()]
          for m in _re.finditer(r'transform="([^"]+)"', data)]
    assert len(ts) == 2
    # grid offsets (-9/+9) compose with the pre-existing translation (100, 50)
    assert sorted(t[3] for t in ts) == [91.0, 109.0]
    assert all(t[7] == 50.0 for t in ts)


