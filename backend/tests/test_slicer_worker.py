def test_embed_gcode_thumbnails_after_header(worker, tmp_path):
    import re as _re
    gcode = tmp_path / "plate_1.gcode"
    gcode.write_text(";HEADER_BLOCK:start\n;foo\n;HEADER_BLOCK_END\nG1 X1\n")
    # use a large source image so both target sizes actually resize
    assert worker.embed_gcode_thumbnails(gcode, _make_png(size=(400, 300))) is True
    text = gcode.read_text()
    begins = _re.findall(r"^; thumbnail begin (\d+)x(\d+) (\d+)$", text, _re.M)
    assert len(begins) == 2  # 300-box + 48-box
    assert text.count("; thumbnail end") == 2
    # inserted right after the header block, original content intact
    assert text.index(";HEADER_BLOCK_END") < text.index("; thumbnail begin")
    assert text.rstrip().endswith("G1 X1")
    # idempotent: second call does not duplicate
    assert worker.embed_gcode_thumbnails(gcode, _make_png(size=(400, 300))) is False
    assert text == gcode.read_text()


