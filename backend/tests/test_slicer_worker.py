def test_build_filament_profiles_overrides_color(worker, tmp_path, monkeypatch):
    tpl = {
        "name": "Snapmaker PLA",
        "filament_settings_id": "SM_PLA",
        "filament_type": "PLA",
        "filament_colour": ["#FFFFFF"],
    }
    (tmp_path / "filament_PLA.json").write_text(json.dumps(tpl))
    monkeypatch.setattr(worker, "FILAMENT_DIR", tmp_path)
    plan = [
        {"slot": 0, "required_hex": "FF0000", "required_material": "PLA",
         "spool": {"id": 3, "color_hex": "E72F1D", "material": "PLA"}},
        {"slot": 1, "required_hex": "0000FF", "required_material": "PETG", "spool": None},
    ]
    paths = worker.build_filament_profiles(tmp_path, plan, {"0": 3})
    assert len(paths) == 4
    f0 = json.loads(Path(paths[0]).read_text())
    assert f0["filament_colour"] == ["#E72F1D"]  # spool color wins
    assert f0["filament_settings_id"] == "SM_PLA_T0"
    f1 = json.loads(Path(paths[1]).read_text())
    assert f1["filament_colour"] == ["#0000FF"]  # falls back to required hex
    f3 = json.loads(Path(paths[3]).read_text())
    assert f3["filament_colour"] == ["#808080"]  # unassigned slot -> neutral gray


def _make_png(color=(255, 0, 0), size=(8, 6)):
    from PIL import Image
    import io as _io
    buf = _io.BytesIO()
    Image.new("RGB", size, color).save(buf, "PNG")
    return buf.getvalue()


def _make_3mf(path, images):
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", b"<xml/>")
        for name, data in images.items():
            z.writestr(name, data)


